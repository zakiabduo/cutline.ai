import type { CaptionSegment, VideoProject } from '../types/studio';
import { splitCaptionIntoWords } from '../utils/shortsEngine';

function makeCaptions(
  items: Array<{ id: string; start: number; end: number; text: string; speaker?: string }>
): CaptionSegment[] {
  return items.map((item) => ({
    ...item,
    words: splitCaptionIntoWords(item.text, item.start, item.end),
  }));
}

